-- ---------- Segurança (RLS): cada usuário vê só o próprio workspace ----------
create or replace function public.is_workspace_member(ws bigint)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.user_workspace
    where workspace_id = ws and user_id = auth.uid()
  );
$$;

alter table public.workspace         enable row level security;
alter table public.user_profile      enable row level security;
alter table public.user_workspace    enable row level security;
alter table public.business_profile  enable row level security;
alter table public.contact           enable row level security;
alter table public.deal              enable row level security;
alter table public.deal_status       enable row level security;
alter table public.pipeline          enable row level security;
alter table public.pipeline_stage    enable row level security;

-- workspace
drop policy if exists "ws select" on public.workspace;
create policy "ws select" on public.workspace for select to authenticated
  using (public.is_workspace_member(workspace_id) or workspace_created_by = auth.uid());
drop policy if exists "ws insert" on public.workspace;
create policy "ws insert" on public.workspace for insert to authenticated
  with check (true);
drop policy if exists "ws update" on public.workspace;
create policy "ws update" on public.workspace for update to authenticated
  using (public.is_workspace_member(workspace_id));

-- user_profile: o próprio perfil e os colegas de workspace
drop policy if exists "perfil select" on public.user_profile;
create policy "perfil select" on public.user_profile for select to authenticated
  using (
    user_id = auth.uid()
    or exists (
      select 1 from public.user_workspace uw
      where uw.user_id = user_profile.user_id and public.is_workspace_member(uw.workspace_id)
    )
  );
drop policy if exists "perfil insert" on public.user_profile;
create policy "perfil insert" on public.user_profile for insert to authenticated
  with check (user_id = auth.uid());
drop policy if exists "perfil update" on public.user_profile;
create policy "perfil update" on public.user_profile for update to authenticated
  using (user_id = auth.uid());

-- user_workspace
drop policy if exists "uw select" on public.user_workspace;
create policy "uw select" on public.user_workspace for select to authenticated
  using (user_id = auth.uid() or public.is_workspace_member(workspace_id));
drop policy if exists "uw insert" on public.user_workspace;
create policy "uw insert" on public.user_workspace for insert to authenticated
  with check (
    (user_id = auth.uid() and exists (
      select 1 from public.workspace w
      where w.workspace_id = user_workspace.workspace_id and w.workspace_created_by = auth.uid()))
    or public.is_workspace_member(workspace_id)
  );

-- tabelas do workspace: membro lê e escreve
do $$
declare t text;
begin
  foreach t in array array['business_profile', 'contact', 'deal'] loop
    execute format('drop policy if exists "membro" on public.%I', t);
    execute format(
      'create policy "membro" on public.%I for all to authenticated
         using (public.is_workspace_member(workspace_id))
         with check (public.is_workspace_member(workspace_id))', t);
  end loop;
end $$;

-- business_profile é criado logo após o workspace, no cadastro
drop policy if exists "bp insert criador" on public.business_profile;
create policy "bp insert criador" on public.business_profile for insert to authenticated
  with check (exists (
    select 1 from public.workspace w
    where w.workspace_id = business_profile.workspace_id and w.workspace_created_by = auth.uid()));

-- listas fixas: leitura para usuários logados
do $$
declare t text;
begin
  foreach t in array array['deal_status', 'pipeline', 'pipeline_stage'] loop
    execute format('drop policy if exists "leitura" on public.%I', t);
    execute format('create policy "leitura" on public.%I for select to authenticated using (true)', t);
  end loop;
end $$;

