-- ---------- Tabelas ----------
create table if not exists public.workspace (
  workspace_id          bigint generated by default as identity primary key,
  workspace_currency    text not null default 'BRL',
  workspace_created_by  uuid default auth.uid() references auth.users (id) on delete set null,
  workspace_created_at  timestamptz not null default now()
);

create table if not exists public.user_profile (
  user_profile_id          bigint generated by default as identity primary key,
  user_id                  uuid not null unique references auth.users (id) on delete cascade,
  user_profile_first_name  text,
  user_profile_last_name   text,
  user_profile_avatar      text,
  user_profile_created_at  timestamptz not null default now()
);

create table if not exists public.user_workspace (
  user_workspace_id  bigint generated by default as identity primary key,
  user_id            uuid not null references auth.users (id) on delete cascade,
  workspace_id       bigint not null references public.workspace (workspace_id) on delete cascade,
  unique (user_id, workspace_id)
);

create table if not exists public.business_profile (
  business_profile_id       bigint generated by default as identity primary key,
  workspace_id              bigint not null unique references public.workspace (workspace_id) on delete cascade,
  business_profile_name     text,
  business_profile_email    text,
  business_profile_phone    text,
  business_profile_website  text
);

create table if not exists public.contact (
  contact_id          bigint generated by default as identity primary key,
  workspace_id        bigint not null references public.workspace (workspace_id) on delete cascade,
  contact_first_name  text not null,
  contact_last_name   text,
  contact_email       text,
  contact_phone       text,
  contact_avatar      text,
  contact_created_by  bigint references public.user_profile (user_profile_id) on delete set null,
  contact_created_at  timestamptz not null default now()
);

create table if not exists public.deal_status (
  deal_status_id    bigint generated by default as identity primary key,
  deal_status_name  text not null unique
);

create table if not exists public.pipeline (
  pipeline_id    bigint generated by default as identity primary key,
  pipeline_name  text not null
);

create table if not exists public.pipeline_stage (
  pipeline_stage_id     bigint generated by default as identity primary key,
  pipeline_id           bigint not null references public.pipeline (pipeline_id) on delete cascade,
  pipeline_stage_name   text not null,
  pipeline_stage_order  int not null default 0
);

create table if not exists public.deal (
  deal_id            bigint generated by default as identity primary key,
  workspace_id       bigint not null references public.workspace (workspace_id) on delete cascade,
  contact_id         bigint references public.contact (contact_id) on delete set null,
  deal_title         text not null,
  deal_description   text,
  deal_value         numeric(14,2) not null default 0,
  deal_status_id     bigint references public.deal_status (deal_status_id),
  pipeline_id        bigint references public.pipeline (pipeline_id),
  pipeline_stage_id  bigint references public.pipeline_stage (pipeline_stage_id),
  deal_created_at    timestamptz not null default now()
);

create index if not exists contact_workspace_idx on public.contact (workspace_id);
create index if not exists deal_workspace_idx    on public.deal (workspace_id);
create index if not exists deal_contact_idx      on public.deal (contact_id);

